package _16_Class.Person;

public class Person {
    String name;
    String email;
    String address;
    String id;

    /*
     * 접근 제어자 4가지가 있음
     * public- 어디서든 접근 가능
     * protected - 같은 패키지 또는 자식 클래스에서만 접근 가능
     * default - 같은 패키지에서만 접근 가능 (명지하지 않으면 default)
     * private - 해당 클래스 내부에서만 접근 가능
     * */
}
